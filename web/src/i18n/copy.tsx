export const uiCopy = { en, zh, ja } as const;

type UiLanguage = keyof typeof uiCopy;

const noticePrefix = "__ohmyrasp_i18n__:";

function normalizeUiLanguage(language?: string): UiLanguage {
  const normalized = language?.toLowerCase().split("-")[0];
  return normalized === "zh" || normalized === "ja" ? normalized : "en";
}

function normalizeValue(language: UiLanguage, value: ReactNode): ReactNode {
  if (typeof value !== "string") {
    return value;
  }
  return translateUiCopy(language, value as UiCopyKey, undefined, { fallbackToInput: true });
}

function interpolate(template: string, values?: UiCopyValues, language: UiLanguage = "en") {
  if (!values) {
    return template;
  }
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    const value = values[key];
    if (value === undefined || value === null) {
      return "";
    }
    return String(normalizeValue(language, value));
  });
}

export function translateUiCopy(
  language: string | undefined,
  key: UiCopyKey,
  values?: UiCopyValues,
  options: { fallbackToInput?: boolean } = {}
) {
  const normalizedLanguage = normalizeUiLanguage(language);
  const dictionary = uiCopy[normalizedLanguage] as Record<string, string | undefined>;
  const english = uiCopy.en as Record<string, string | undefined>;
  const template = dictionary[key] ?? (options.fallbackToInput ? key : english[key] ?? `__MISSING_TRANSLATION:${key}__`);
  return interpolate(template, values, normalizedLanguage);
}

export function useUiCopy() {
  const { i18n } = useTranslation();
  const language = normalizeUiLanguage(i18n.resolvedLanguage ?? i18n.language);
  return {
    language,
    copy: (key: UiCopyKey, values?: UiCopyValues) => translateUiCopy(language, key, values),
    copyLoose: (value: string) => translateUiCopy(language, value as UiCopyKey, undefined, { fallbackToInput: true })
  };
}

export function UiText({ k, values }: { k: UiCopyKey; values?: UiCopyValues }) {
  const { copy } = useUiCopy();
  return <>{copy(k, values)}</>;
}

export function UiValue({ value }: { value?: string | null }) {
  const { copyLoose } = useUiCopy();
  return <>{value ? copyLoose(value) : copyLoose("unknown")}</>;
}

export function notice(key: UiCopyKey, values?: UiCopyValues) {
  return `${noticePrefix}${JSON.stringify({ key, values: values ?? {} })}`;
}

export function translateNotice(language: string | undefined, value: string) {
  if (!value) {
    return "";
  }
  if (!value.startsWith(noticePrefix)) {
    return translateUiCopy(language, value as UiCopyKey, undefined, { fallbackToInput: true });
  }
  try {
    const parsed = JSON.parse(value.slice(noticePrefix.length)) as { key?: UiCopyKey; values?: UiCopyValues };
    return parsed.key ? translateUiCopy(language, parsed.key, parsed.values) : value;
  } catch {
    return value;
  }
}
