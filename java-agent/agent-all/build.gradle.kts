import com.github.jengelman.gradle.plugins.shadow.tasks.ShadowJar
import java.io.File
import java.security.MessageDigest
import java.util.Properties
import java.util.jar.JarFile
import java.util.zip.ZipFile

// The universal agent: the four lines, one copy of the shared classes and of shaded ASM, and the
// launcher (io.ohmyrasp.agent.launch.AgentLauncher, in :shared) that starts the line fitting the
// running Java. Nothing is compiled here; the JARs are assembled from the other modules.
plugins {
    java
    id("com.gradleup.shadow")
}

// Every agent JAR carries one launcher entry class, its own (generated by shared/src/entryGenerator):
// the JVM loads a Premain-Class by name, so two JARs must never share one.
val otherLauncherEntries = listOf("UniversalEntry", "PrimaryEntry", "Java17Entry", "Java11Entry", "Java8Entry")
    .filter { it != "UniversalEntry" }
    .map { "io/ohmyrasp/agent/launch/$it.class" }

val launcher = "io.ohmyrasp.agent.launch.UniversalEntry"

// The highest class-file major version each input may hold: a line's own classes may use its own
// release; the launcher, the shared classes and ASM must load on Java 8.
val majorLimits = mapOf(
    ":agent-java8" to 52,
    ":agent-java11" to 55,
    ":agent-java17" to 61,
    ":agent-jdk25" to 65,
    ":shared" to 52,
)
val externalMajorLimit = 52

dependencies {
    for (line in listOf(":agent-java8", ":agent-java11", ":agent-java17", ":agent-jdk25")) {
        implementation(project(line))
    }
}

/**
 * Class-file helpers for the task actions. An object, not script functions: a task action that calls a
 * script function captures the script, which the configuration cache (check-agent.sh) cannot store.
 */
object ClassFiles {
    /** Every class entry of a JAR or class directory, by internal path, with its bytes. */
    fun entries(file: File): Sequence<Pair<String, ByteArray>> =
        if (file.isDirectory) {
            file.walkTopDown().filter { it.isFile && it.name.endsWith(".class") }
                .map { it.relativeTo(file).invariantSeparatorsPath to it.readBytes() }
                .toList().asSequence()
        } else {
            ZipFile(file).use { zip ->
                zip.entries().asSequence()
                    .filter { !it.isDirectory && it.name.endsWith(".class") }
                    .map { it.name to zip.getInputStream(it).use { input -> input.readBytes() } }
                    .toList().asSequence()
            }
        }

    fun packaged(name: String) = !name.startsWith("META-INF/") && !name.endsWith("module-info.class")

    fun major(bytes: ByteArray): Int {
        require(bytes.size >= 8 && (bytes[0].toInt() and 0xFF) == 0xCA && (bytes[1].toInt() and 0xFF) == 0xFE) {
            "not a class file"
        }
        return ((bytes[6].toInt() and 0xFF) shl 8) or (bytes[7].toInt() and 0xFF)
    }
}

// Resolved once per build; each entry knows which project, if any, produced it.
val runtimeArtifacts = configurations.runtimeClasspath.flatMap { it.incoming.artifacts.resolvedArtifacts }

val verifyAgentAllInputs = tasks.register("verifyAgentAllInputs") {
    group = "verification"
    description = "Fails when two inputs of the universal JAR hold the same class name with different contents."
    val artifacts = runtimeArtifacts
    inputs.files(configurations.runtimeClasspath)
    doLast {
        val seen = HashMap<String, Pair<String, String>>()
        val clashes = sortedSetOf<String>()
        for (artifact in artifacts.get()) {
            for ((name, bytes) in ClassFiles.entries(artifact.file)) {
                if (!ClassFiles.packaged(name)) continue
                val digest = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
                val previous = seen.putIfAbsent(name, digest to artifact.file.name)
                if (previous != null && previous.first != digest) {
                    clashes += "$name (${previous.second} and ${artifact.file.name})"
                }
            }
        }
        require(clashes.isEmpty()) {
            "These classes come from two inputs with different contents; the universal JAR would keep only the " +
                "first:\n  " + clashes.joinToString("\n  ")
        }
    }
}

fun ShadowJar.universalContent(title: String) {
    // DuplicatesStrategy.EXCLUDE keeps the first of two same-named entries. Check that no two inputs
    // differ before every build of these JARs, not only under `check`: build scripts call the JAR tasks
    // directly.
    dependsOn(verifyAgentAllInputs)
    archiveClassifier.set("")
    archiveVersion.set("")
    duplicatesStrategy = DuplicatesStrategy.EXCLUDE
    configurations = listOf(project.configurations.runtimeClasspath.get())
    manifest {
        attributes(
            "Premain-Class" to launcher,
            "Agent-Class" to launcher,
            "Can-Redefine-Classes" to "true",
            "Can-Retransform-Classes" to "true",
            "Implementation-Title" to title,
        )
    }
    relocate("org.objectweb.asm", "io.ohmyrasp.agent.shaded.asm")
    exclude(otherLauncherEntries)
    exclude("**/module-info.class", "META-INF/versions/**")
}

val agentAllJar = tasks.register<ShadowJar>("agentAllJar") {
    group = "build"
    description = "Builds the universal agent JAR: every line, started by the launcher on the Java it fits."
    archiveBaseName.set("ohmyrasp-agent-all")
    universalContent("OhMyRasp Java Agent (every line)")
}

val shirudoMode = (providers.gradleProperty("shirudoMode").orNull ?: "block").trim().lowercase()
require(shirudoMode in setOf("block", "monitor")) {
    "shirudoMode must be 'block' or 'monitor', got: '$shirudoMode'"
}
val shirudoLockConfig = (providers.gradleProperty("shirudoLockConfig").orNull ?: "true").trim().lowercase()
require(shirudoLockConfig in setOf("true", "false")) {
    "shirudoLockConfig must be 'true' or 'false', got: '$shirudoLockConfig'"
}

val shirudoGeneratedDir = layout.buildDirectory.dir("generated/shirudo")

val generateShirudoDefaults = tasks.register("generateShirudoDefaults") {
    group = "build"
    description = "Generates META-INF/ohmyrasp-shirudo.properties for the universal shirudo upatch jar."
    val outDir = shirudoGeneratedDir
    // Local copies: a task action that reads the script's own properties cannot be stored in the configuration cache.
    val mode = shirudoMode
    val lockConfig = shirudoLockConfig
    inputs.property("shirudoMode", mode)
    inputs.property("shirudoLockConfig", lockConfig)
    outputs.dir(outDir)
    doLast {
        val propsFile = outDir.get().file("META-INF/ohmyrasp-shirudo.properties").asFile
        propsFile.parentFile.mkdirs()
        propsFile.writeText(
            """
            standalone=true
            lock_config=$lockConfig
            mode=$mode
            control=none
            log=stderr
            latency_sample=0
            """.trimIndent() + "\n",
            Charsets.UTF_8
        )
    }
}

// Named like the per-line shirudo tasks; the file is ohmyrasp.jar.
val shirudoUpatchJar = tasks.register<ShadowJar>("shirudoUpatchJar") {
    group = "build"
    description = "Builds the universal standalone shirudo upatch agent jar."
    dependsOn(generateShirudoDefaults)
    archiveBaseName.set("ohmyrasp")
    universalContent("OhMyRasp Java Agent (every line / shirudo upatch)")
    manifest {
        attributes("OhMyRasp-Shirudo-Upatch" to "true")
    }
    from(shirudoGeneratedDir)
}

val shirudoProperties = "META-INF/ohmyrasp-shirudo.properties"

val verifyAgentAllJars = tasks.register("verifyAgentAllJars") {
    group = "verification"
    description = "Verifies the universal JARs: manifests, class-file versions per input, shirudo size and properties."
    val general = agentAllJar.flatMap { it.archiveFile }
    val shirudo = shirudoUpatchJar.flatMap { it.archiveFile }
    val artifacts = runtimeArtifacts
    val limits = majorLimits
    val externalLimit = externalMajorLimit
    val mode = shirudoMode
    val lockConfig = shirudoLockConfig
    val launcherClass = launcher
    val excludedEntries = otherLauncherEntries
    val propertiesEntry = shirudoProperties
    inputs.file(general)
    inputs.file(shirudo)
    inputs.files(configurations.runtimeClasspath)
    inputs.property("shirudoMode", mode)
    inputs.property("shirudoLockConfig", lockConfig)
    doLast {
        // Which input each packaged class comes from decides how new its class file may be.
        val limitByClass = HashMap<String, Pair<Int, String>>()
        for (artifact in artifacts.get()) {
            val id = artifact.id.componentIdentifier
            val origin = if (id is ProjectComponentIdentifier) id.projectPath else id.displayName
            val limit = if (id is ProjectComponentIdentifier) {
                limits[id.projectPath] ?: error("No class-file limit for project ${id.projectPath}")
            } else {
                externalLimit
            }
            for ((name, _) in ClassFiles.entries(artifact.file)) {
                if (!ClassFiles.packaged(name)) continue
                val packagedName = if (name.startsWith("org/objectweb/asm/")) {
                    "io/ohmyrasp/agent/shaded/asm/" + name.removePrefix("org/objectweb/asm/")
                } else {
                    name
                }
                if (packagedName !in excludedEntries) limitByClass.putIfAbsent(packagedName, limit to origin)
            }
        }
        val launcherEntry = launcherClass.replace('.', '/') + ".class"
        require(limitByClass[launcherEntry]?.second == ":shared") {
            "The launcher $launcherEntry must come from :shared, found ${limitByClass[launcherEntry]?.second}"
        }

        for (jarFile in listOf(general.get().asFile, shirudo.get().asFile)) {
            require(jarFile.isFile) { "Missing ${jarFile.absolutePath}" }
            JarFile(jarFile).use { jar ->
                val attributes = jar.manifest?.mainAttributes ?: error("Missing manifest in ${jarFile.name}")
                require(attributes.getValue("Premain-Class") == launcherClass) { "Unexpected Premain-Class in ${jarFile.name}" }
                require(attributes.getValue("Agent-Class") == launcherClass) { "Unexpected Agent-Class in ${jarFile.name}" }
                require(attributes.getValue("Boot-Class-Path") == null) {
                    "${jarFile.name} must not carry Boot-Class-Path: each line appends its own JAR"
                }
                val tooNew = mutableListOf<String>()
                val unknown = mutableListOf<String>()
                var classCount = 0
                var propertiesCount = 0
                for (entry in jar.entries().asSequence()) {
                    if (entry.name == propertiesEntry) propertiesCount++
                    if (entry.isDirectory || !entry.name.endsWith(".class")) continue
                    require(ClassFiles.packaged(entry.name)) { "Unexpected ${entry.name} in ${jarFile.name}" }
                    classCount++
                    val (limit, origin) = limitByClass[entry.name] ?: run { unknown += entry.name; continue }
                    val found = jar.getInputStream(entry).use { ClassFiles.major(it.readNBytes(8)) }
                    if (found > limit) tooNew += "${entry.name}: major $found > $limit ($origin)"
                    if (entry.name == launcherEntry) require(found == 49) {
                        "${jarFile.name}: the launcher entry $launcherEntry is class-file version $found, expected 49"
                    }
                }
                require(unknown.isEmpty()) { "Classes in ${jarFile.name} that no input provides: $unknown" }
                require(tooNew.isEmpty()) { "Class files too new for their line in ${jarFile.name}:\n  " + tooNew.joinToString("\n  ") }
                require(classCount == limitByClass.size) {
                    "${jarFile.name} holds $classCount classes, its inputs ${limitByClass.size}"
                }
                val isShirudo = jarFile == shirudo.get().asFile
                if (!isShirudo) {
                    require(propertiesCount == 0) { "${jarFile.name} must not carry $propertiesEntry" }
                    return@use
                }
                require(jarFile.length() < 16L * 1024L * 1024L) {
                    "${jarFile.name} exceeds the 16 MiB shirudo limit: ${jarFile.length()} bytes"
                }
                require(attributes.getValue("OhMyRasp-Shirudo-Upatch") == "true") {
                    "Missing OhMyRasp-Shirudo-Upatch: true in ${jarFile.name}"
                }
                require(propertiesCount == 1) { "${jarFile.name} carries $propertiesEntry $propertiesCount times" }
                val props = Properties()
                jar.getInputStream(jar.getJarEntry(propertiesEntry)).use { props.load(it.reader(Charsets.UTF_8)) }
                val expected = mapOf(
                    "standalone" to "true", "lock_config" to lockConfig, "mode" to mode,
                    "control" to "none", "log" to "stderr", "latency_sample" to "0",
                )
                for ((key, value) in expected) {
                    require(props.getProperty(key) == value) { "Expected $key=$value, got ${props.getProperty(key)}" }
                }
            }
        }
    }
}

tasks.assemble {
    dependsOn(agentAllJar, shirudoUpatchJar)
}

tasks.check {
    dependsOn(verifyAgentAllInputs, verifyAgentAllJars)
}
